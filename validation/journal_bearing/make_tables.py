"""Emit the README result tables straight from the result JSONs.

Hand-transcribing forty numbers out of a log into a markdown table is exactly the
kind of step that silently introduces an error into a validation report, so the
tables in README.md are generated by this script rather than typed.

Usage:  $PY make_tables.py > tables.md
"""
import json, os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from raimondi_boyd import RB_TABLE
import ferron as F

HERE = os.path.dirname(os.path.abspath(__file__))


def load(name):
    p = os.path.join(HERE, name)
    return json.load(open(p)) if os.path.exists(p) else None


def rb_tables(rb):
    print("### Free-boundary resolution audit\n")
    print("Rupture angle at L/D = 8, eps = 0.6 against the exact infinite-length")
    print("Swift-Stieber solution (213.08 deg).  That exact solution reproduces the")
    print("L/D = inf block of the Raimondi & Boyd table to 0.6% in S and 0.4 deg in")
    print("attitude angle, which is what makes it usable as the reference here.\n")
    print("| beta [Pa] | n_theta | rupture [deg] | error [deg] | S | S error |")
    print("|---|---|---|---|---|---|")
    rows = rb.get("convergence") or []
    if not rows:
        # The sweep can be run with do_convergence=False; fall back to the audit
        # recorded in run_raimondi_boyd.CONVERGENCE_MEASURED.
        from raimondi_boyd import swift_stieber_infinite
        from run_raimondi_boyd import CONVERGENCE_MEASURED
        ex = swift_stieber_infinite(0.6)
        rows = [dict(r, S_exact=ex["S"], phi_exact=ex["phi_deg"],
                     rupture_exact=ex["t2_deg"]) for r in CONVERGENCE_MEASURED]
    for r in rows:
        print(f"| {r['beta']:.0e} | {r['nth']} | {r['rupture']:.2f} | "
              f"{r['rupture'] - r['rupture_exact']:+.2f} | {r['S']:.5f} | "
              f"{(r['S'] - r['S_exact']) / r['S_exact']:+.1%} |")

    for ld_key in ("0.5", "1"):
        print(f"\n### L/D = {ld_key}, fed film (supply groove at the maximum gap)\n")
        print("| eps | mu [Pa.s] | S sim | S chart | dS | phi sim [deg] | "
              "phi chart [deg] | dphi [deg] | rupture [deg] | p_max/beta | converged |")
        print("|---|---|---|---|---|---|---|---|---|---|---|")
        rows = [r for r in rb["sweep"] if r["ld_key"] == ld_key and r["inlet"] == "flooded"]
        for r in sorted(rows, key=lambda r: (r["eps"], -r["mu"])):
            print(f"| {r['eps']:.1f} | {r['mu']:.3f} | {r['S']:.5f} | {r['S_ref']:.4f} | "
                  f"{r['dS']:+.1%} | {r['phi']:.2f} | {r['phi_ref']:.2f} | "
                  f"{r['dphi']:+.2f} | {r['rupture']:.2f} | {r['p_over_beta']:.4f} | "
                  f"{r['converged']} |")

    print("\n### Ungrooved (the optical-rig configuration)\n")
    print("| L/D | eps | load [N] | p_max gauge [Pa] | theta_min | "
          "S sim | S chart |")
    print("|---|---|---|---|---|---|---|")
    rows = [r for r in rb["sweep"] if r["inlet"] == "ungrooved" and abs(r["mu"] - 0.01) < 1e-9]
    for r in sorted(rows, key=lambda r: (r["ld_key"], r["eps"])):
        print(f"| {r['ld_key']} | {r['eps']:.1f} | {r['W']:.3f} | "
              f"{r['p_max'] - 1.0e5:.4g} | {r['theta_min']:.3e} | "
              f"{r['S']:.4g} | {r['S_ref']:.4f} |")


def ferron_tables(fr):
    px, pm = F.measured_peak_pressure_mpa()
    tx, tm = F.measured_peak_temperature_c()
    lo, hi = F.measured_rupture_xpi()
    print("\n### Ferron reference point (W = 4 kN, 2000 rpm)\n")
    print("Every case is run at the eccentricity that carries the measured 4 kN,")
    print("because Alakhramsing Figure 9 is specified by load.\n")
    print("| case | eps for 4 kN | p_max [MPa] | vs meas | p_max X/pi | vs meas [deg] | "
          "rupture X/pi | peak-to-rupture [deg] | T_max [C] | vs meas [K] | "
          "Q [l/min] | R_p | max dp per coupling iter [Pa] |")
    print("|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for tag in ("thd_adiabatic", "thd_metalbush", "isothermal"):
        m = fr.get(tag)
        if not m:
            continue
        # R_p is the max pressure change between coupling iterations normalised by
        # property_reference_pressure (1e5 Pa), so R_p * 1e5 is the change in Pa --
        # a far more meaningful convergence statement than pass/fail against an
        # arbitrarily tight tolerance.
        print(f"| {tag} | {m['eps_for_4kN']:.3f} | {m['p_max_MPa']:.3f} | "
              f"{(m['p_max_MPa'] - pm) / pm:+.1%} | {m['p_max_xpi']:+.3f} | "
              f"{(m['p_max_xpi'] - px) * 180:+.1f} | {m['rupture_xpi']:+.3f} | "
              f"{m['peak_to_rupture_deg']:.1f} | {m['T_max_C']:.2f} | "
              f"{m['T_max_C'] - tm:+.2f} | {m['Q_lpm']:.2f} | {m['R_p']:.1e} | "
              f"{m['R_p'] * 1e5:.3g} |")
    print(f"\nMeasured: p_max = {pm:.2f} MPa at X/pi = {px:+.2f}; "
          f"T_max = {tm:.1f} C at X/pi = {tx:+.2f} (rise {tm - F.T_SUPPLY_C:.1f} K); "
          f"rupture bracketed by X/pi = {lo:+.2f}..{hi:+.2f}, i.e. "
          f"{(lo - px) * 180:.0f}-{(hi - px) * 180:.0f} deg past the peak.")

    if fr.get("resolution"):
        print("\n### Mesh resolution check (THD, adiabatic)\n")
        print("| mesh | p_max [MPa] | p_max X/pi | rupture X/pi | T_max [C] | load [N] |")
        print("|---|---|---|---|---|---|")
        for r in fr["resolution"]:
            print(f"| {r['nth']}x{r['nz']} | {r['p_max_MPa']:.4f} | {r['p_max_xpi']:+.4f} | "
                  f"{r['rupture_xpi']:+.4f} | {r['T_max_C']:.3f} | {r['W_N']:.0f} |")

    if fr.get("load_curve"):
        print("\n### Load capacity against Ferron Figure 10a\n")
        print("| eps (measured) | W measured [N] | W simulated [N] | error |")
        print("|---|---|---|---|")
        for r in sorted(fr["load_curve"], key=lambda r: r["eps"]):
            print(f"| {r['eps']:.2f} | {r['W_meas']:.0f} | {r['W_sim']:.0f} | "
                  f"{(r['W_sim'] - r['W_meas']) / r['W_meas']:+.1%} |")


def main():
    rb = load("raimondi_boyd_results.json")
    if rb:
        rb_tables(rb)
    fr = load("ferron_results.json")
    if fr:
        ferron_tables(fr)


if __name__ == "__main__":
    main()
