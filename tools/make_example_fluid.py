"""Write the SYNTHETIC example oil-refrigerant pair and load table shipped with the GUI.

Example data only, not for design. Nothing here is measured or supplied data:

- Oil: an ISO VG 68 grade oil. The grade fixes 68 mm2/s at 40 degC (ISO 3448);
  8.7 mm2/s at 100 degC is an assumed viscosity index near 100. Between and beyond
  these points the Walther relation log10(log10(nu + 0.7)) = A - B log10(T) is used.
- Refrigerant "RX": fictitious. Liquid kinematic viscosity 0.15 mm2/s at 20 degC
  with a mild temperature dependence; vapour pressure from Clausius-Clapeyron,
  p_v = 14 bar at 20 degC and 45 bar at 70 degC (invented round values).
- Solution: Raoult's law on mole fractions (molar masses 72 g/mol refrigerant,
  600 g/mol oil, both assumed); viscosity by logarithmic mass-fraction mixing.

Usage:  python tools/make_example_fluid.py  [output root, default: repository root]
Writes  fluids/example_vg68_rx/{pair.txt,solution.csv} and
        examples/load_table_example.csv
        examples/load_table_rotating.csv
"""

import math
import sys
from pathlib import Path

ROOT = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parents[1]
NOTE = "SYNTHETIC EXAMPLE ONLY, NOT FOR DESIGN"

# Oil: Walther fit through the two grade points.
T40, T100 = 313.15, 373.15
NU40, NU100 = 68.0, 8.7
W40 = math.log10(math.log10(NU40 + 0.7))
W100 = math.log10(math.log10(NU100 + 0.7))
B_WALTHER = (W40 - W100) / (math.log10(T100) - math.log10(T40))
A_WALTHER = W40 + B_WALTHER * math.log10(T40)


def nu_oil(t_k):
    return 10 ** (10 ** (A_WALTHER - B_WALTHER * math.log10(t_k))) - 0.7


def nu_refrigerant(t_k):
    return 0.15 * math.exp(800.0 * (1.0 / t_k - 1.0 / 293.15))


# Refrigerant vapour pressure, Clausius-Clapeyron through two invented points.
P20, P70 = 14e5, 45e5
B_VAP = math.log(P70 / P20) / (1.0 / 293.15 - 1.0 / 343.15)
A_VAP = math.log(P20) + B_VAP / 293.15
M_REF, M_OIL = 72.0, 600.0


def mole_fraction(w):
    n_ref = w / M_REF
    return n_ref / (n_ref + (1.0 - w) / M_OIL)


def saturation_temperature(w, p_pa):
    """Temperature at which content w is saturated at pressure p (Raoult)."""
    x = mole_fraction(w)
    return B_VAP / (A_VAP - math.log(p_pa / x))


def nu_mix(w, t_k):
    return math.exp((1.0 - w) * math.log(nu_oil(t_k)) + w * math.log(nu_refrigerant(t_k)))


def write_pair():
    folder = ROOT / "fluids" / "example_vg68_rx"
    folder.mkdir(parents=True, exist_ok=True)
    rows = []
    for t_c in range(-20, 141, 10):
        rows.append((0.0, float(t_c), None, nu_oil(t_c + 273.15)))
    pressures_bar = [1, 2, 4, 6, 8, 10, 15, 20, 25, 30, 40, 50]
    for w in [0.05, 0.10, 0.15, 0.20, 0.25, 0.30, 0.40, 0.50]:
        for p_bar in pressures_bar:
            t_k = saturation_temperature(w, p_bar * 1e5)
            t_c = t_k - 273.15
            if -40.0 <= t_c <= 150.0:
                rows.append((w, t_c, p_bar / 10.0, nu_mix(w, t_k)))
    with open(folder / "solution.csv", "w", newline="\n") as f:
        f.write("c_mass_fraction,T_C,P_MPa,viscosity_mm2s\n")
        for w, t_c, p_mpa, nu in rows:
            f.write(f"{w:.2f},{t_c:.4f},{'' if p_mpa is None else f'{p_mpa:.2f}'},{nu:.6g}\n")
    (folder / "pair.txt").write_text(
        "# Oil-refrigerant pair for the pancake GUI. Format: fluids/README.md\n"
        f"# {NOTE}. Generated by tools/make_example_fluid.py.\n"
        "name = Example VG68 oil + RX (synthetic)\n"
        "oil = ISO VG 68 example oil (grade viscosity, Walther fit)\n"
        "refrigerant = RX (fictitious)\n"
        "source = synthetic: ISO VG 68 grade point, assumed VI ~100, Raoult's law, "
        "invented vapour pressure (tools/make_example_fluid.py)\n"
        f"note = {NOTE}\n"
        "# No gas-phase block: this example runs FBNS only (no gas transport).\n"
        "density_intercept_kg_m3 = 885\n"
        "density_slope_kg_m3_K = -0.62\n"
        "oil_vapour_pressure_Pa = 500\n"
        "specific_heat_J_kgK = 2000\n"
        "thermal_conductivity_W_mK = 0.13\n"
        "table = solution.csv\n",
        newline="\n")
    return len(rows)


def write_load_table():
    folder = ROOT / "examples"
    folder.mkdir(parents=True, exist_ok=True)
    with open(folder / "load_table_example.csv", "w", newline="\n") as f:
        f.write(f"# {NOTE}. Synthetic cyclic load: 2000 + 800 sin(phi) + 300 sin(2 phi + 30 deg) N,\n")
        f.write("# direction 90 deg (fixed frame). Columns: crank angle [deg], magnitude [N], direction [deg]\n")
        f.write("crank_angle_deg,load_N,direction_deg\n")
        for phi in range(0, 360, 2):
            r = math.radians(phi)
            load = 2000.0 + 800.0 * math.sin(r) + 300.0 * math.sin(2.0 * r + math.radians(30.0))
            f.write(f"{phi},{load:.3f},90\n")


def write_rotating_load_table():
    """Synthetic rotating load: the direction turns once per revolution, as on a
    crank-driven compressor bearing; the magnitude varies twice per revolution."""
    folder = ROOT / "examples"
    with open(folder / "load_table_rotating.csv", "w", newline="\n") as f:
        f.write(f"# {NOTE}. Synthetic rotating load: 1800 + 400 sin(2 phi) N,\n")
        f.write("# direction 270 + phi deg (fixed frame, turns once per revolution).\n")
        f.write("# Columns: crank angle [deg], magnitude [N], direction [deg]\n")
        f.write("crank_angle_deg,load_N,direction_deg\n")
        for phi in range(0, 360, 2):
            r = math.radians(phi)
            load = 1800.0 + 400.0 * math.sin(2.0 * r)
            f.write(f"{phi},{load:.3f},{(270.0 + phi) % 360.0:.1f}\n")


if __name__ == "__main__":
    count = write_pair()
    write_load_table()
    write_rotating_load_table()
    print(f"wrote {count} table rows and the example load table under {ROOT}")
